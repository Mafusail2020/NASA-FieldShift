"""Fetch NASA POWER daily point data, clean it, average per oblast, write a sanity report.

Run by hand: python -m pipeline.fetch_power
"""
import time
from pathlib import Path

import numpy as np
import pandas as pd
import requests

API = "https://power.larc.nasa.gov/api/temporal/daily/point"
PARAMS = ["T2M_MAX", "T2M_MIN", "T2MDEW", "WS2M", "ALLSKY_SFC_SW_DWN", "PRECTOTCORR", "SNODP"]
START, END = "19910101", "20251231"
MISSING = -999.0
RAW_DIR = Path(__file__).resolve().parents[1] / "data" / "raw" / "power"

# 4-8 points per oblast were requested; Ivan chose to keep the points that passed the checks.
OBLASTS = {
    "vinnytska": [(49.6, 28.0), (49.0, 28.8), (48.6, 27.6), (49.2, 29.4)],
    "poltavska": [(50.0, 33.3), (49.9, 34.2), (49.2, 34.0)],
    "kirovohradska": [(48.7, 31.3), (48.5, 32.5), (48.9, 33.0)],
    "odeska": [(47.5, 30.0), (46.8, 30.5), (47.0, 29.8)],
}


def parse_power(payload: dict) -> tuple[pd.DataFrame, dict]:
    """POWER JSON -> (DataFrame indexed by date, units as received).

    -999 becomes NaN. Radiation in kWh/m2/day is converted to MJ/m2/day (x3.6).
    """
    units = {p: v.get("units") for p, v in payload["parameters"].items()}
    df = pd.DataFrame(payload["properties"]["parameter"]).astype(float)
    df.index = pd.to_datetime(df.index, format="%Y%m%d")
    df.index.name = "date"
    df = df.replace(MISSING, np.nan)
    rad_units = units.get("ALLSKY_SFC_SW_DWN", "")
    if rad_units.lower().replace(" ", "").startswith("kw-hr") or rad_units.lower().startswith("kwh"):
        df["ALLSKY_SFC_SW_DWN"] = df["ALLSKY_SFC_SW_DWN"] * 3.6
    return df, units


def fetch_point(lat: float, lon: float, retries: int = 4, params: list = PARAMS) -> dict:
    q = dict(parameters=",".join(params), community="ag", latitude=lat, longitude=lon,
             start=START, end=END, format="json")
    for attempt in range(retries):
        try:
            r = requests.get(API, params=q, timeout=120)
            r.raise_for_status()
            return r.json()
        except requests.RequestException as e:
            if attempt == retries - 1:
                raise
            wait = 5 * 2 ** attempt
            print(f"  retry in {wait}s: {e}")
            time.sleep(wait)


def report(name: str, mean: pd.DataFrame, points: list, units: dict, n_missing: dict) -> str:
    rain = mean["PRECTOTCORR"].groupby(mean.index.year).sum()
    july = mean.loc[mean.index.month == 7, "T2M_MAX"].mean()
    lines = [f"## {name}", "",
             f"- points: {points}",
             f"- radiation units as received: `{units.get('ALLSKY_SFC_SW_DWN')}` (stored as MJ/m^2/day)",
             f"- mean July Tmax: {july:.1f} °C",
             f"- annual precipitation, mean of years: {rain.mean():.0f} mm (min {rain.min():.0f} in {rain.idxmin()}, max {rain.max():.0f} in {rain.idxmax()})",
             f"- missing values per point (all params): {n_missing}",
             "", "| year | precip, mm |", "|---|---|"]
    lines += [f"| {y} | {v:.0f} |" for y, v in rain.items()]
    return "\n".join(lines) + "\n"


def main():
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    sections = []
    for name, points in OBLASTS.items():
        frames, n_missing, units = [], {}, {}
        for i, (lat, lon) in enumerate(points, 1):
            print(f"{name}_{i}: {lat}, {lon}")
            df, units = parse_power(fetch_point(lat, lon))
            n_missing[f"{lat},{lon}"] = int(df.isna().sum().sum())
            header = f"# lat={lat} lon={lon} units={units}\n"
            with open(RAW_DIR / f"{name}_{i}.csv", "w") as f:
                f.write(header)
                df.to_csv(f)
            frames.append(df)
            time.sleep(2)
        for a in range(len(frames)):
            for b in range(a + 1, len(frames)):
                if frames[a].equals(frames[b]):
                    print(f"WARNING {name}: points {a+1} and {b+1} give identical data (same POWER cell)")
        mean = sum(frames) / len(frames)
        mean.to_csv(RAW_DIR / f"{name}_mean.csv")
        sections.append(report(name, mean, points, units, n_missing))
    text = "# NASA POWER sanity report\n\nDaily, community=AG, 1991-2025. Generated by `pipeline/fetch_power.py`.\n\n" + "\n".join(sections)
    (RAW_DIR / "README.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
